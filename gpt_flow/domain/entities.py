import time
import uuid
from typing import Any

from pydantic import BaseModel, Field

from gpt_flow.domain.enums import AuthorRole, StreamEventType


class AuthCredentials(BaseModel):
    """Holds authenticated session tokens, cookies, and identity metadata."""

    access_token: str = Field(..., description="OpenAI OAuth Bearer JWT")
    device_id: str = Field(..., description="OpenAI Device ID (UUID format)")
    cookies: dict[str, str] = Field(
        default_factory=dict, description="Session and Cloudflare cookies"
    )
    user_id: str | None = Field(default=None, description="OpenAI User UUID")
    account_id: str | None = Field(default=None, description="ChatGPT Account UUID")
    plan_type: str | None = Field(
        default="free", description="Subscription plan type (free, plus, team)"
    )
    email: str | None = Field(default=None, description="User email address")
    expires_at: int | None = Field(
        default=None, description="Unix timestamp of token expiry"
    )

    def is_expired(self, buffer_seconds: int = 60) -> bool:
        """Check if JWT is expired with safety margin."""
        if not self.expires_at:
            return False
        return time.time() >= (self.expires_at - buffer_seconds)


class SentinelTokens(BaseModel):
    """Security tokens generated by the Sentinel defense system."""

    chat_requirements_token: str = Field(
        ..., description="Encrypted token from sentinel finalize"
    )
    proof_token: str = Field(..., description="Proof-of-Work and fingerprint token")
    turnstile_token: str | None = Field(
        default=None, description="Cloudflare Turnstile token"
    )
    created_at: float = Field(
        default_factory=time.time, description="Creation timestamp"
    )

    def is_fresh(self, max_age_seconds: int = 180) -> bool:
        """Check if sentinel token is within valid window (default 3 minutes)."""
        return (time.time() - self.created_at) < max_age_seconds


class MessageNode(BaseModel):
    """A single message node within a conversation tree."""

    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    parent_id: str | None = None
    role: AuthorRole
    content: str
    thinking_content: str | None = None
    create_time: float = Field(default_factory=time.time)
    system_hints: list[str] = Field(default_factory=list)


class ConversationTree(BaseModel):
    """A conversation maintaining a directed acyclic graph (DAG) of messages."""

    conversation_id: str | None = None
    title: str | None = None
    current_node_id: str | None = None
    messages: dict[str, MessageNode] = Field(default_factory=dict)

    def add_message(
        self,
        role: AuthorRole,
        content: str,
        thinking_content: str | None = None,
        parent_id: str | None = None,
        system_hints: list[str] | None = None,
    ) -> MessageNode:
        """Add a new message node and update the current pointer."""
        pid = parent_id or self.current_node_id
        node = MessageNode(
            parent_id=pid,
            role=role,
            content=content,
            thinking_content=thinking_content,
            system_hints=system_hints or [],
        )
        self.messages[node.id] = node
        self.current_node_id = node.id
        return node

    def get_parent_id(self) -> str:
        """Return parent message ID for the next user turn."""
        return self.current_node_id or "client-created-root"


class ChatRequest(BaseModel):
    """Specification for sending a prompt to the LLM."""

    prompt: str
    model: str = "auto"
    conversation_id: str | None = None
    parent_message_id: str | None = None
    thinking_enabled: bool = False
    language: str = "zh-TW"


class ChatResponseChunk(BaseModel):
    """A streaming delta chunk received from the assistant."""

    event_type: StreamEventType
    text: str = ""
    thinking_text: str = ""
    message_id: str | None = None
    conversation_id: str | None = None
    is_finished: bool = False
    metadata: dict[str, Any] = Field(default_factory=dict)


class TelemetryData(BaseModel):
    """Performance telemetry data sent after stream completion."""

    server_request_id: str
    model: str = "auto"
    preflight_time_ms: float = 0.0
    count_tokens: int = 0
    ts_first_token_ms: float = 0.0
    ts_max_token_time_ms: float = 0.0
    ts_mean_token_without_first_ms: float = 0.0
    ts_total_request_ms: float = 0.0
